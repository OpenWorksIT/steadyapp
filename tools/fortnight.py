#!/usr/bin/env python3
"""Draws the home page's fortnight: the line from Steady's mark stretched over the two weeks
between sessions, a dot per daily check-in (coloured by the app's mood scale), one missed day,
and the mark's sun for the next session. Writes layouts/_partials/fortnight.html and assets/css/fortnight.css (no inline styles:
the site's Content-Security-Policy doesn't allow them).
Run from the repository root: python3 tools/fortnight.py"""
import math

W, TOP, H = 1200, 40, 280          # viewBox: x 0..1200, y 40..320
x0, x1, base = 60, 1060, 196


def y(x):
    t = (x - x0) / (x1 - x0)       # 0..1 across the fortnight: unsettled, then steady
    amp = 74 * math.exp(-3.4 * t) * (1 - t) ** 0.6
    return base - amp * math.sin(2 * math.pi * t * 3.1 + 0.4)


line = [(x0 + i * (x1 - x0) / 240, 0) for i in range(241)]
d = "M" + " L".join(f"{x:.1f} {y(x):.1f}" for x, _ in line) + f" L1150 {y(x1):.1f}"
days = [(x0 + 40 + i * (x1 - x0 - 40) / 13, 0) for i in range(14)]
days = [(x, y(x)) for x, _ in days]
mood = [2, 1, 2, 3, 2, None, 3, 3, 4, 4, 3, 4, 4, 5]   # None: missed
scale = ["#BCD0DC", "#8BAEC2", "#5A88A3", "#2C5F7C", "#1F4B62"]
note_day = 9

svg = [f'<svg class="fortnight" viewBox="0 {TOP} {W} {H}" role="img" aria-labelledby="fortnight-title fortnight-desc">',
       '<title id="fortnight-title">Two weeks between sessions</title>',
       '<desc id="fortnight-desc">A line that starts unsettled after one session and grows steady by the next, '
       'with a dot for each day the patient checked in and one missed day.</desc>',
       f'<path class="fortnight-line" d="{d}" pathLength="1"/>',
       f'<g class="fortnight-start"><circle cx="{x0}" cy="{base}" r="15"/></g>']
for i, (x, yy) in enumerate(days):
    if mood[i] is None:
        svg.append(f'<circle class="day day-missed d{i}" cx="{x:.1f}" cy="{yy:.1f}" r="9"/>')
    else:
        svg.append(f'<circle class="day d{i}" fill="{scale[mood[i] - 1]}" cx="{x:.1f}" cy="{yy:.1f}" r="11"/>')
svg += ['<circle class="fortnight-sun" cx="1130" cy="96" r="40"/>',
        f'<text class="fortnight-label" x="{x0}" y="{base + 56}">Session</text>',
        f'<text class="fortnight-label" x="1130" y="{base + 56}" text-anchor="middle">Next session</text>',
        f'<text class="fortnight-label fortnight-label-soft" x="{days[5][0]:.0f}" y="{days[5][1] + 48:.0f}" text-anchor="middle">missed</text>',
        '</svg>']
nx, ny = days[note_day]
with open("layouts/_partials/fortnight.html", "w") as f:
    f.write("{{- /* The home page's fortnight. Generated by tools/fortnight.py: edit there, then run it. */ -}}\n")
    f.write('<div class="fortnight-wrap">\n')
    f.write("\n".join(svg))
    f.write(f'\n<p class="fortnight-note" aria-hidden="true"><span>Day {note_day + 1}</span> Slept better. The walk with my sister helped.</p>\n</div>\n')

with open("assets/css/fortnight.css", "w") as f:
    f.write("/* Generated by tools/fortnight.py */\n")
    f.write(f".fortnight-note {{ left: {nx / W * 100:.2f}%; top: {(ny - TOP) / H * 100:.2f}%; }}\n")
    f.write("@media (prefers-reduced-motion: no-preference) {\n")
    for i in range(len(days)):
        f.write(f"  .fortnight .d{i} {{ animation-delay: {0.45 + i * 0.14:.2f}s; }}\n")
    f.write("}\n")
